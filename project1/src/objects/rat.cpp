Mesh build_rat() {
	Mesh modelled;
	append(modelled, kRatFur , kFur );
	append(modelled, kRatSkin, kSkin);

	Mesh rat;
	append(rat, modelled,
		  scaling(kRatScale, kRatScale, kRatScale)
		* translation(-kMiddleX, -kMiddleY, -kMiddleZ)
	);
	return rat;
}
